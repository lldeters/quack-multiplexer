package engine

import (
	"context"
	"errors"
	"time"

	"quackmux/internal/config"
)

// Phase is the provider-level state of an engine instance.
type Phase string

const (
	// PhaseStarting: created, not yet accepting Quack connections.
	PhaseStarting Phase = "Starting"
	// PhaseReady: the Quack endpoint answers.
	PhaseReady Phase = "Ready"
	// PhaseFailed: the instance will never become (or stay) ready.
	PhaseFailed Phase = "Failed"
	// PhaseGone: the instance no longer exists.
	PhaseGone Phase = "Gone"
)

// Instance is a provider's view of one engine.
type Instance struct {
	// ID is unique and stable for the lifetime of the engine (pod name).
	ID string
	// Key is the engine key the instance serves. Warm pool instances carry a
	// key with an empty owner until they are claimed.
	Key Key
	// Warm marks an unclaimed warm-pool instance.
	Warm bool
	// ProfileName is the profile the instance was launched from.
	ProfileName string
	// SpecHash identifies the rendered launch spec (to detect profile changes).
	SpecHash string
	Phase    Phase
	// Endpoint is the base URL of the Quack server, e.g. http://10.1.2.3:9494.
	// Set once the instance is ready.
	Endpoint string
	// Token authenticates the gateway at the engine.
	Token string
	// User is the user whose session caused the launch (for per-user limits).
	User string
	// CreatedAt is the launch time.
	CreatedAt time.Time
	// Message explains the phase (e.g. "ImagePullBackOff: ...").
	Message string
	// Volume names the data volume of an engine of a persistent profile
	// (the PersistentVolumeClaim its pod mounts); empty otherwise.
	Volume string
	// ReplaceDue is when the replacement of an engine of a persistent
	// profile fell due, as recorded on the instance (see
	// ReplacementRecorder); zero if it did not.
	ReplaceDue time.Time
}

// LaunchRequest asks a provider to start an engine.
type LaunchRequest struct {
	// ID was obtained from the provider's NewID and must be used verbatim.
	ID          string
	Key         Key
	Warm        bool
	User        string
	ProfileName string
	Profile     config.Profile
	// Token is generated by the manager; the provider must hand it to the
	// engine (QUACK_TOKEN) and store it so that List can return it later.
	Token    string
	SpecHash string
	// Fence, if set, must report true right before the provider creates the
	// instance; otherwise Launch fails with ErrNotLeader. The manager sets
	// it for persistent keys with leader election: a leader that resumes
	// after a freeze must not start a second engine on a data volume next
	// to the one the new leader started meanwhile (see persistence.go).
	Fence func() bool
}

// ErrNotSupported is returned by providers that cannot perform an operation
// (for example launching engines with the static provider).
var ErrNotSupported = errors.New("operation not supported by this engine provider")

// Provider runs engines. Implementations must be safe for concurrent use.
type Provider interface {
	// Name identifies the provider ("kubernetes", "process", "static").
	Name() string
	// CanLaunch reports whether Launch is supported.
	CanLaunch() bool
	// NewID proposes a fresh, unique instance id for a key (for Kubernetes a
	// valid pod name such as quack-user-alice-x7k2p). Launch must use it.
	NewID(key Key, warm bool) string
	// SpecHash returns the hash of the spec that Launch would render for
	// the profile. Engines with a different hash are outdated.
	SpecHash(profileName string, profile config.Profile) string
	// Run starts background machinery (informers, health probes) and blocks
	// until ctx is cancelled. Events must only be read after Run started.
	Run(ctx context.Context) error
	// WaitSynced blocks until the provider's view is complete (initial list
	// done), so that List returns every existing instance.
	WaitSynced(ctx context.Context) error
	// List returns all instances owned by this gateway instance.
	List(ctx context.Context) ([]Instance, error)
	// Launch creates an instance and returns it in PhaseStarting (or
	// PhaseReady). It must not wait for readiness.
	Launch(ctx context.Context, req LaunchRequest) (Instance, error)
	// Claim re-keys an unclaimed warm instance for a session of user. The
	// user is kept like that of a launched instance (Instance.User), so that
	// a restarted gateway still counts the engine against
	// limits.maxEnginesPerUser.
	Claim(ctx context.Context, id string, key Key, user string) error
	// Terminate stops an instance and releases its resources. Terminating
	// an unknown instance is not an error.
	Terminate(ctx context.Context, id string, reason string) error
	// Events delivers instance updates (phase, endpoint, message changes,
	// and PhaseGone on deletion). The channel is closed when Run returns.
	Events() <-chan Instance
}
